#!/usr/bin/env node
// Generate code from the schemas (no runtime dependency on a validator library):
//   src/protocol/generated/ from spec/openapi.yaml (the contract):
//     spec.ts        version, limited-tracking lists, event catalog, schema list
//     validators.ts  Ajv standalone validators for every schema
//     types.ts       TypeScript types for every schema
//   src/policy/generated/ from schemas/data-policy.schema.json:
//     data-policy-validator.ts  validator for data policy documents
// Usage: node scripts/generate.mjs           write the files
//        node scripts/generate.mjs --check   fail if the files are not up to date
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

import { Ajv2020 } from 'ajv/dist/2020.js'
import standaloneCodeModule from 'ajv/dist/standalone/index.js'
import addFormatsModule from 'ajv-formats'
import { parse } from 'yaml'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const specPath = join(root, '..', 'spec', 'openapi.yaml')
const srcDir = join(root, 'src')
const dataPolicySchemaPath = join(root, 'schemas', 'data-policy.schema.json')
const SCHEMA_ID = 'urn:clearideas:analytics:v1'
const HEADER =
  '// Generated by server/scripts/generate.mjs from spec/openapi.yaml. Do not edit.\n' +
  '// Run `npm run generate` in server/ after changing the spec.\n'

const standaloneCode = standaloneCodeModule.default ?? standaloneCodeModule
const addFormats = addFormatsModule.default ?? addFormatsModule

export function loadSpec(path = specPath) {
  return parse(readFileSync(path, 'utf8'))
}

/** components.schemas with "#/components/schemas/X" refs rewritten to "#/$defs/X". */
export function schemaDefs(spec) {
  return JSON.parse(
    JSON.stringify(spec.components.schemas).split('#/components/schemas/').join('#/$defs/'),
  )
}

/** A configured Ajv instance with every schema of the spec registered (also used by tests). */
export function createAjv(spec, { source = false } = {}) {
  const ajv = new Ajv2020({
    strict: true,
    allowUnionTypes: true,
    allErrors: true,
    ...(source ? { code: { source: true, esm: true } } : {}),
  })
  addFormats(ajv)
  ajv.addKeyword('example')
  ajv.addSchema({ $id: SCHEMA_ID, $defs: schemaDefs(spec) })
  return ajv
}

// --- validators.ts ------------------------------------------------------------------

// Runtime references Ajv emits, and their replacements in src/protocol/runtime.ts.
const RUNTIME_REFS = [
  [/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g, 'ucs2length'],
  [/require\("ajv-formats\/dist\/formats"\)\.fullFormats\[("[^"]+")\]/g, 'formats[$1]'],
]

/** Point Ajv's runtime references at src/protocol/runtime.ts; fail on anything else. */
function rewriteRuntimeRefs(code) {
  for (const [pattern, replacement] of RUNTIME_REFS) code = code.replace(pattern, replacement)
  const leftover = code.match(/require\([^)]*\)/g)
  if (leftover) {
    throw new Error(
      `Generated validators need runtime code not provided by src/protocol/runtime.ts: ${[
        ...new Set(leftover),
      ].join(', ')}`,
    )
  }
  for (const format of code.matchAll(/formats\["([^"]+)"\]/g)) {
    if (!['date-time'].includes(format[1])) {
      throw new Error(`Format "${format[1]}" is not provided by src/protocol/runtime.ts`)
    }
  }
  return code
}

function generateValidators(spec) {
  const names = Object.keys(spec.components.schemas)
  const ajv = createAjv(spec, { source: true })
  let code = rewriteRuntimeRefs(
    standaloneCode(ajv, Object.fromEntries(names.map(name => [name, `${SCHEMA_ID}#/$defs/${name}`]))),
  )
  // Replace Ajv's `export const Name = validateN;` with one typed export.
  const exported = {}
  code = code.replace(/export const (\w+) = (\w+);/g, (_, name, fn) => {
    exported[name] = fn
    return ''
  })
  if (Object.keys(exported).length !== names.length) {
    throw new Error('Unexpected standalone output: not every schema was exported')
  }
  code = code.replace(/^"use strict";/, '')
  const entries = names.map(name => `  ${JSON.stringify(name)}: ${exported[name]},`).join('\n')
  return (
    HEADER +
    '// Ajv standalone code (MIT); see THIRD_PARTY_NOTICES.md.\n' +
    '/* eslint-disable */\n' +
    '// @ts-nocheck\n' +
    "import { formats, ucs2length } from '../runtime.ts'\n" +
    "import type { CompiledValidator } from '../validator-types.ts'\n" +
    "import type { SchemaName } from './spec.ts'\n\n" +
    code.trim() +
    '\n\n/** One compiled validator per schema in components.schemas. */\n' +
    `export const validators: Record<SchemaName, CompiledValidator> = {\n${entries}\n}\n`
  )
}

// --- spec.ts --------------------------------------------------------------------------

/** Own property names of the event catalog schemas and everything they compose (allOf). */
function catalogProperties(spec, catalog) {
  const schemas = spec.components.schemas
  const names = new Set(['FullEventContext', 'Attribution', ...Object.values(catalog)])
  for (const name of [...names]) {
    for (const part of schemas[name].allOf ?? []) names.add(part.$ref.split('/').pop())
  }
  const result = {}
  for (const name of [...names].sort()) {
    result[name] = {
      properties: Object.keys(schemas[name].properties ?? {}),
      allOf: (schemas[name].allOf ?? []).map(part => part.$ref.split('/').pop()),
    }
  }
  return result
}

function generateSpecData(spec) {
  const names = Object.keys(spec.components.schemas)
  const catalog = Object.fromEntries(
    Object.entries(spec['x-event-catalog'].events).map(([event, ref]) => [
      event,
      ref.split('/').pop(),
    ]),
  )
  const limited = spec['x-limited-tracking']
  const json = value => JSON.stringify(value, null, 2)
  return (
    HEADER +
    '\n' +
    `/** Version of the contract (spec/openapi.yaml info.version). */\n` +
    `export const SPEC_VERSION = ${JSON.stringify(spec.info.version)}\n\n` +
    `/** Names of the schemas in components.schemas. */\n` +
    `export const SCHEMA_NAMES = ${json(names)} as const\n\n` +
    `export type SchemaName = (typeof SCHEMA_NAMES)[number]\n\n` +
    `/** What a \`limited\` event may contain (x-limited-tracking). */\n` +
    `export const LIMITED_TRACKING = {\n` +
    `  events: ${json(limited.events)},\n` +
    `  fields: ${json(limited.fields)},\n` +
    `} as const\n\n` +
    `/** Props schema of each standard event (x-event-catalog). */\n` +
    `export const EVENT_CATALOG = ${json(catalog)} as const\n\n` +
    `export type StandardEventName = keyof typeof EVENT_CATALOG\n\n` +
    `/** Documented props of the catalog schemas (own properties; see allOf for the rest). */\n` +
    `export const CATALOG_PROPERTIES = ${json(catalogProperties(spec, catalog))} as const\n`
  )
}

// --- types.ts -------------------------------------------------------------------------

const refName = ref => ref.split('/').pop()

function doc(text, indent) {
  if (!text) return ''
  const lines = String(text).trim().split('\n')
  if (lines.length === 1) return `${indent}/** ${lines[0].replace(/\*\//g, '*\\/')} */\n`
  return `${indent}/**\n${lines.map(l => `${indent} * ${l.replace(/\*\//g, '*\\/')}`.trimEnd()).join('\n')}\n${indent} */\n`
}

function typeOf(schema, indent) {
  if (schema.$ref) return refName(schema.$ref)
  if ('const' in schema) return JSON.stringify(schema.const)
  if (schema.enum) return schema.enum.map(v => JSON.stringify(v)).join(' | ')
  const parts = []
  if (schema.allOf) parts.push(...schema.allOf.map(part => typeOf(part, indent)))
  const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : []
  const variants = types.map(type => {
    switch (type) {
      case 'string':
        return 'string'
      case 'number':
      case 'integer':
        return 'number'
      case 'boolean':
        return 'boolean'
      case 'null':
        return 'null'
      case 'array':
        return `Array<${schema.items ? typeOf(schema.items, indent) : 'unknown'}>`
      case 'object':
        return objectType(schema, indent, !!schema.allOf)
      default:
        throw new Error(`Unsupported type ${type}`)
    }
  })
  if (variants.length) parts.push(variants.length > 1 ? variants.join(' | ') : variants[0])
  if (!parts.length) return 'unknown'
  return parts.filter(part => part !== '{}').join(' & ') || '{}'
}

function objectType(schema, indent, inAllOf) {
  const inner = `${indent}  `
  const required = new Set(schema.required ?? [])
  const lines = []
  for (const [name, property] of Object.entries(schema.properties ?? {})) {
    const key = /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name)
    lines.push(
      `${doc(property.description, inner)}${inner}${key}${required.has(name) ? '' : '?'}: ${typeOf(property, inner)}`,
    )
  }
  const additional = schema.additionalProperties
  if (additional && typeof additional === 'object') {
    lines.push(`${inner}[key: string]: ${typeOf(additional, inner)}`)
  } else if (additional === undefined && !inAllOf) {
    // Open object: other properties are allowed.
    lines.push(`${inner}[key: string]: unknown`)
  }
  if (!lines.length) return '{}'
  return `{\n${lines.join('\n')}\n${indent}}`
}

function generateTypes(spec) {
  const out = [HEADER]
  for (const [name, schema] of Object.entries(spec.components.schemas)) {
    out.push(`${doc(schema.description, '')}export type ${name} = ${typeOf(schema, '')}\n`)
  }
  return out.join('\n')
}

// --- data-policy-validator.ts ----------------------------------------------------------

export function loadDataPolicySchema(path = dataPolicySchemaPath) {
  return JSON.parse(readFileSync(path, 'utf8'))
}

/** Ajv configured for the data policy schema (also used by tests). */
export function createDataPolicyAjv(schema = loadDataPolicySchema(), { source = false } = {}) {
  const ajv = new Ajv2020({
    strict: true,
    allErrors: true,
    ...(source ? { code: { source: true, esm: true } } : {}),
  })
  ajv.addSchema(schema)
  return ajv
}

function generateDataPolicyValidator(schema) {
  const ajv = createDataPolicyAjv(schema, { source: true })
  let code = rewriteRuntimeRefs(standaloneCode(ajv, { validateDataPolicy: schema.$id }))
  code = code.replace(/^"use strict";/, '')
  const match = code.match(/export const validateDataPolicy = (\w+);/)
  if (!match) throw new Error('Unexpected standalone output for the data policy schema')
  code = code.replace(match[0], '')
  const imports = code.includes('ucs2length') ? "import { ucs2length } from '../../protocol/runtime.ts'\n" : ''
  return (
    HEADER.replace('spec/openapi.yaml', 'server/schemas/data-policy.schema.json').replace(
      'after changing the spec',
      'after changing the schema',
    ) +
    '// Ajv standalone code (MIT); see THIRD_PARTY_NOTICES.md.\n' +
    '/* eslint-disable */\n' +
    '// @ts-nocheck\n' +
    imports +
    "import type { CompiledValidator } from '../../protocol/validator-types.ts'\n\n" +
    code.trim() +
    `\n\n/** Validates a data policy document against schemas/data-policy.schema.json. */\n` +
    `export const validateDataPolicyDocument: CompiledValidator = ${match[1]}\n`
  )
}

// --- main -----------------------------------------------------------------------------

/** Generated files, by path relative to src/. */
export function generate(spec = loadSpec(), dataPolicySchema = loadDataPolicySchema()) {
  return {
    'protocol/generated/spec.ts': generateSpecData(spec),
    'protocol/generated/validators.ts': generateValidators(spec),
    'protocol/generated/types.ts': generateTypes(spec),
    'policy/generated/data-policy-validator.ts': generateDataPolicyValidator(dataPolicySchema),
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = generate()
  const check = process.argv.includes('--check')
  const stale = []
  for (const [name, content] of Object.entries(files)) {
    const path = join(srcDir, name)
    if (check) {
      let current = null
      try {
        current = readFileSync(path, 'utf8')
      } catch {}
      if (current !== content) stale.push(relative(root, path))
    } else {
      mkdirSync(dirname(path), { recursive: true })
      writeFileSync(path, content)
    }
  }
  if (check && stale.length) {
    console.error(
      `Out of date with spec/openapi.yaml: ${stale.join(', ')}. Run \`npm run generate\` in server/.`,
    )
    process.exit(1)
  }
  console.log(check ? 'Generated files are up to date.' : `Wrote ${Object.keys(files).join(', ')}`)
}
